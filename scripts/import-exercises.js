// Builds src/exercise-data.js from free-exercise-db (public domain):
// https://github.com/yuhonas/free-exercise-db
//
// Usage:
//   node scripts/import-exercises.js                 # download the pinned version
//   node scripts/import-exercises.js exercises.json  # use a local copy
import { readFile, writeFile } from "node:fs/promises";

// Pinned so the data and image URLs never change under us.
export const SOURCE_COMMIT = "f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5";
const BASE = `https://raw.githubusercontent.com/yuhonas/free-exercise-db/${SOURCE_COMMIT}`;
const OUT = new URL("../src/exercise-data.js", import.meta.url);

// Dataset muscle -> our dial. Neck has no dial and is skipped.
const MUSCLE_MAP = {
  chest: "chest",
  lats: "back",
  "middle back": "back",
  "lower back": "back",
  traps: "back",
  shoulders: "shoulders",
  biceps: "biceps",
  triceps: "triceps",
  forearms: "forearms",
  abdominals: "abs",
  quadriceps: "quads",
  hamstrings: "hamstrings",
  glutes: "glutes",
  abductors: "glutes",
  adductors: "glutes",
  calves: "calves",
};

// Stretching and cardio don't fit a sets-and-reps workout.
const SKIP_CATEGORIES = new Set(["stretching", "cardio"]);

function repsFor(e) {
  if (["powerlifting", "strongman", "olympic weightlifting"].includes(e.category)) return "3-6";
  if (e.category === "plyometrics") return "5-8";
  if (e.mechanic === "compound") return "6-10";
  if (e.mechanic === "isolation") return "10-15";
  return "8-12";
}

const raw = process.argv[2]
  ? JSON.parse(await readFile(process.argv[2], "utf8"))
  : await (await fetch(`${BASE}/dist/exercises.json`)).json();

const exercises = raw
  .filter((e) => !SKIP_CATEGORIES.has(e.category))
  .filter((e) => e.images.length > 0 && e.instructions.length > 0)
  .filter((e) => MUSCLE_MAP[e.primaryMuscles[0]])
  .map((e) => ({
    id: e.id,
    name: e.name,
    primary: MUSCLE_MAP[e.primaryMuscles[0]],
    secondary: [...new Set(e.secondaryMuscles.map((m) => MUSCLE_MAP[m]).filter(Boolean))],
    level: e.level,
    equipment: e.equipment || "none",
    category: e.category,
    reps: repsFor(e),
    instructions: e.instructions,
    images: e.images,
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const header = `// GENERATED by scripts/import-exercises.js, do not edit by hand.
// Source: free-exercise-db (public domain), commit ${SOURCE_COMMIT}
// ${exercises.length} exercises.
export const IMAGE_BASE = "${BASE}/exercises/";
`;
await writeFile(OUT, `${header}export const EXERCISES = ${JSON.stringify(exercises)};\n`);

const counts = {};
for (const e of exercises) counts[e.primary] = (counts[e.primary] || 0) + 1;
console.log(`Wrote ${exercises.length} exercises`, counts);
